@patch("fastapi.templating.Jinja2Templates.TemplateResponse")
def test_create_task(mock_template):
    """???? ???????? ?????? ? ?????? ?? ?????????? ?? SQLite"""
    # ?????????? ????? ?????????? ?????? ???????? ????? ?????? ?????????? HTML
    mock_template.return_value = Response(status_code=303)
    
    response = client.post("/task/create", data={"title": "Test CI Task", "description": "Verify database write"})
    
    # ????????? ???????????? ??????-????
    assert response.status_code == 303
    
    # ?????????, ??? ?????? ????????? ?????????? ?? ?????????? ?? SQLite
    with sqlite3.connect(DB_PATH) as conn:
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()
        cursor.execute("SELECT * FROM tasks WHERE title='Test CI Task'")
        task = cursor.fetchone()
        
    assert task is not None
    assert task["description"] == "Verify database write"

